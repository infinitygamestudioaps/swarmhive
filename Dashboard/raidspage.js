    var gk = null, town = null;
    (route.steps || []).forEach(function (s) { if (s.do === 'gk' && !gk) gk = s; if (s.do === 'town' && !town) town = s; });
    var cs = cut >= 0 ? route.steps[cut] : null;
    var out = { pts: pts, start: null, landing: '', L: null, partial: cs ? (cs.do === 'floor' ? 'the floor teleporter ' + ((cs.npc && cs.npc.name) || '') : cs.do === 'enter' ? 'the entry at ' + ((cs.npc && cs.npc.name) || cs.how || '') : 'a by-hand step') : '' };
    if (gk && gk.desc) { out.landing = gk.desc; out.start = { kind: 'gk', desc: gk.desc }; if (Array.isArray(gk.landing)) out.L = { desc: gk.desc, x: gk.landing[0], y: gk.landing[1], z: gk.landing[2] }; }
    else if (town && town.town) { out.start = { kind: 'town', town: String(town.town) }; if (Array.isArray(town.at)) out.L = { desc: '.' + String(town.town).toLowerCase() + ' landing', x: town.at[0], y: town.at[1], z: town.at[2] }; }
    return out;
