  /** small preview (boss page Facts): dashed cyan path, start dot, boss dot; onReady re-renders when the fetch lands */
  function factsHtml(id, onReady) {
    const v = cached(id);
    if (!v) { get(id).then(() => { try { onReady && onReady(); } catch (e) { } }); return '<span class="muted">loading…</span>'; }
    const ed = `#/raid/${encodeURIComponent(id)}/route`;
    if (!v.route) return `<span class="muted">none in the nav atlas</span>`;
    const S = raSummary(v.route);
    if (S.bad) return `<span class="ra-st bad">${esc2(S.status)}</span> <span>${esc2((S.why[0] || 'no reason given').slice(0, 220))}</span> <a href="${ed}">route editor ›</a>`;
    const pts = raWalkPts(v.route); let svg = '';
    if (pts.length > 1) {
      const xs = pts.map(p => p.x), ys = pts.map(p => p.y), x0 = Math.min(...xs), x1 = Math.max(...xs), y0 = Math.min(...ys), y1 = Math.max(...ys);
      const w = Math.max(1, x1 - x0), h = Math.max(1, y1 - y0), k = Math.min(108 / w, 48 / h), ox = (120 - w * k) / 2, oy = (60 - h * k) / 2;
      const pt = (q) => (ox + (q.x - x0) * k).toFixed(1) + ',' + (oy + (q.y - y0) * k).toFixed(1);
      const a = pt(pts[0]).split(','), e = pt(pts[pts.length - 1]).split(',');
      svg = `<svg class="ra-thumb" viewBox="0 0 120 60" aria-hidden="true"><polyline points="${pts.map(pt).join(' ')}" fill="none" stroke="${RA_COL.walk}" stroke-width="1.6" stroke-dasharray="4 2.5" stroke-linejoin="round"/><circle cx="${a[0]}" cy="${a[1]}" r="2.6" fill="${RA_COL.landing}"/><circle cx="${e[0]}" cy="${e[1]}" r="3.2" fill="#f0c040"/></svg>`;
    }
    return `<a class="ra-prev" href="${ed}" title="open the route editor with the computed path">${svg}<span><span class="ra-st ${esc2(S.status)}">${esc2(S.status)}</span> ${km2(S.len)} · ${secTxt(S.sec)}<br><span class="muted">${esc2(S.chain.slice(0, 120))}</span></span></a>`;
  }
  /** unreachable / blocked bosses for list badges (circuit page): { <id>: { status, why } }, refreshed every 5 min, onReady after a fetch */
  function badMap(onReady) {
    if (LISTS.map && Date.now() - LISTS.at < 300000) return LISTS.map;
    if (!LISTS.p) LISTS.p = Promise.all(['unreachable', 'blocked'].map(st => api('/api/navatlas?list=' + st).catch(() => ({ rows: [] })))).then(rs => {
      const m = {};
      rs.forEach((d, i) => { const cols = d.cols || [], ki = Math.max(0, cols.indexOf('key')), wi = cols.indexOf('why'); (d.rows || []).forEach(row => { const k = String(row[ki] || ''); if (!/^raid:/.test(k)) return; m[k.slice(5)] = { status: i ? 'blocked' : 'unreachable', why: wi >= 0 ? String(row[wi] || '') : '' }; }); });
      LISTS.map = m; LISTS.at = Date.now(); LISTS.p = null; try { onReady && onReady(); } catch (e) { }
    });
    return LISTS.map || {};
  }
