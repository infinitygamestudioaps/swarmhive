// (index.html routeEditor / routeMapSvg / renderRouteEd) only knew the saved / recorded / locked routes; a boss without one showed a straight
// landing -> spawn line. The nav atlas (docs/plan/tools/nav_atlas.js -> Scripts/data/nav_atlas, GET /api/navatlas?key=raid:<id>, Dashboard/
// navatlas_api.js) has a computed route per boss: town > gk (landing) > walk {points flat x,y,z triplets, how geodata|town-graph|saved|straight}
// > door / floor / enter / need > arrive, with status ok | unverified | conditional | blocked | unreachable + why. This block:
//   * draws it as its own layer in the editor map (dashed cyan + dots; straight legs orange; door / floor / enter / need markers) + legend,
//   * shows status / length / time / why above the map (unreachable / blocked: the reason, nothing to prefill),
//   * prefills the editable list from it when the boss has NO saved route ("computed — not saved yet"; Save & lock keeps it),
//   * "Use computed path" replaces the list with it (uiConfirm), * the boss page Facts preview + the circuit list badges.
