// SKILL ENCHANT PAGE API (user 2026-10-12: "add the skill enchant for each char's skills", forum topic 2753 "Skill Enchant Table").
// Loaded by server.js (one hook, BEFORE the key check like fundpage_api.js). Public (no secrets): /skillenchantpage.js, /skillenchantpage.css,
// /skillenchant_logic.js.
//   GET  /api/skillenchant                    { generated, books, rules, levels, settings, rev, planAt, parties: [{ leader, chars: [summary] }] }
//                                             summary = { name, level, cls, targetName, eligible, why, online, sp, adena, top: [{ id, name, icon, route }], count, totals }
//   GET  /api/skillenchant?name=X[&level=N][&live=1]   one character in full (Dashboard/skillenchant_logic.js recommendChar with the per-level table);
//                                             live=1 asks MCP get_account_data type=skills (cached 90 s) for the real skill levels / enchant routes.
//   POST /api/skillenchant { settings, rev }  sanitized (seSanitize), lock + rev check (409), history copy (Scripts/data/history/), atomic write of
//                                             Scripts/data/skill_enchant_settings.json, then the bots' plan Scripts/data/skill_enchant_plan.json is rebuilt.
// Data: Scripts/data/skill_enchant.json (GENERATED by docs/plan/tools/skill_enchant.js; re-read when it changes on disk).
// Env for tests: SWARM_SE_SETTINGS_FILE, SWARM_SE_PLAN_FILE.
'use strict';
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const L = require('./skillenchant_logic.js');
const STATIC = { '/skillenchantpage.js': 'application/javascript; charset=utf-8', '/skillenchantpage.css': 'text/css; charset=utf-8', '/skillenchant_logic.js': 'application/javascript; charset=utf-8' };
const NAME_RE = /^[A-Za-z0-9_\-]{1,40}$/;
const sha = (t) => t ? crypto.createHash('sha1').update(t).digest('hex').slice(0, 16) : '';
const isoNow = () => new Date().toISOString();
let G = null;
function guard(ctx) { if (!G) G = require(path.join(ctx.ROOT, 'docs', 'plan', 'tools', 'manual_guard.js')); return G; }
const settingsFile = (ctx) => process.env.SWARM_SE_SETTINGS_FILE || ctx.seSettingsFile || path.join(ctx.DATA, 'skill_enchant_settings.json');
const planFile = (ctx) => process.env.SWARM_SE_PLAN_FILE || ctx.sePlanFile || path.join(ctx.DATA, 'skill_enchant_plan.json');
const dataFile = (ctx) => ctx.seDataFile || path.join(ctx.DATA, 'skill_enchant.json');

// ------------------------------------------------------------------------------------------------- data (cached by mtime)
const DC = { file: '', mtime: 0, data: null };
function data(ctx) {
  const F = dataFile(ctx);
  let st = null; try { st = fs.statSync(F); } catch (e) { return null; }
  if (DC.data && DC.file === F && DC.mtime === st.mtimeMs) return DC.data;
  try { DC.data = JSON.parse(fs.readFileSync(F, 'utf8').replace(/^﻿/, '')); DC.file = F; DC.mtime = st.mtimeMs; } catch (e) { return null; }
  return DC.data;
}
function readSettings(ctx) {
  const F = settingsFile(ctx);
  let raw = ''; try { raw = fs.readFileSync(F, 'utf8'); } catch (e) { }
  let j = null; try { j = raw ? JSON.parse(raw.replace(/^﻿/, '')) : {}; } catch (e) { return { raw, rev: sha(raw), data: null, broken: e.message, exists: true }; }
  if (!j || typeof j !== 'object' || Array.isArray(j)) j = {};
  return { raw, rev: sha(raw), data: j, exists: !!raw };
}
function cfgFresh(ctx) {
  try { return JSON.parse(fs.readFileSync(path.join(ctx.ROOT, 'swarm.config.json'), 'utf8').replace(/^﻿/, '')); } catch (e) { }
  try { return ctx.reloadCfg() || {}; } catch (e) { return {}; }
}
function classTree(ctx) { return ctx.readJson(path.join(ctx.DATA, 'class_tree.json'), { classes: {} }) || { classes: {} }; }
function casterPrimary(ctx) { return ctx.readJson(path.join(ctx.DATA, 'caster_primary.json'), null); }
function chars(ctx) {
  const states = {}; (ctx.readStates() || []).forEach(s => { states[s.name] = s; });
  return L.charactersFrom(cfgFresh(ctx), states, classTree(ctx));
}

// ------------------------------------------------------------------------------------------------- live skills via MCP (optional)
const LIVE = {};   // name -> { at, skills: { id: level }, sp, err }
function withTimeout(p, ms) { return Promise.race([p, new Promise((_, rej) => setTimeout(() => rej(new Error('timeout')), ms))]); }
/** MCP get_account_data type=skills -> { id: level } (field names vary: id / Id / skill_id, level / Level) */
function parseSkills(txt) {
  let j = null; try { j = JSON.parse(txt); } catch (e) { return null; }
  const list = Array.isArray(j) ? j : (j && (j.skills || j.items || j.data)) || null;
  if (!Array.isArray(list)) return null;
  const out = {};
  list.forEach(s => { if (!s || typeof s !== 'object') return; const id = Number(s.id ?? s.Id ?? s.skill_id ?? s.skillId), lv = Number(s.level ?? s.Level ?? s.skill_level ?? s.lvl); if (id > 0 && lv > 0) out[id] = lv; });
  return out;
}
async function liveSkills(ctx, name) {
  const c = LIVE[name]; if (c && Date.now() - c.at < 90000) return c;
  const out = { at: Date.now(), skills: null, err: '' };
  if (!ctx.mcpCallChar) { out.err = 'no MCP'; return (LIVE[name] = out); }
  try { const t = await withTimeout(ctx.mcpCallChar('get_account_data', name, { type: 'skills' }), 10000); out.skills = parseSkills(t); if (!out.skills) out.err = String(t).slice(0, 120); }
  catch (e) { out.err = String(e.message || e).slice(0, 120); }
  return (LIVE[name] = out);
}

// ------------------------------------------------------------------------------------------------- read
function summary(d, ch, settings, cp) {
  const r = L.recommendChar(d, ch, settings, { primary: L.primaryFrom(cp, ch) });
  return { name: r.name, party: r.party, level: r.level, cls: r.cls, classId: r.classId, targetName: r.targetName, targetFrom: r.targetFrom, role: r.role, eligible: r.eligible, why: r.why,
    online: r.online, sp: r.sp, adena: r.adena, auto: r.settings.auto, charAuto: r.settings.charAuto, count: r.skills.length,
    top: r.skills.filter(x => x.chosen.route).slice(0, 4).map(x => ({ id: x.id, name: x.name, icon: x.icon, route: x.chosen.name })), totals: r.totals, pricedAt: r.pricedAt };
}
function info(ctx) {
  const d = data(ctx); if (!d) return { error: 'Scripts/data/skill_enchant.json is missing — run: node docs/plan/tools/skill_enchant.js --plan' };
  const S = readSettings(ctx), settings = Object.assign({}, L.DEFAULT_SETTINGS, S.data || {}), cp = casterPrimary(ctx);
  const list = chars(ctx), byParty = {};
  list.forEach(ch => { const p = ch.party || '(no party)'; (byParty[p] = byParty[p] || []).push(summary(d, ch, settings, cp)); });
  let planAt = null; try { planAt = fs.statSync(planFile(ctx)).mtime.toISOString(); } catch (e) { }
  return { generated: d.meta && d.meta.generated, counts: d.meta && d.meta.counts, books: d.books, bookSources: d.bookSources, rules: d.rules, levels: d.levels,
    forumVsDatapack: d.forumVsDatapack && d.forumVsDatapack.note, settings, rev: S.rev, broken: S.broken || null, planAt,
    parties: Object.keys(byParty).map(p => ({ leader: p, chars: byParty[p] })) };
}
async function detail(ctx, name, level, wantLive) {
  const d = data(ctx); if (!d) return { error: 'Scripts/data/skill_enchant.json is missing' };
  const ch = chars(ctx).find(c => c.name === name); if (!ch) return { error: `unknown character ${name}` };
  const S = readSettings(ctx), settings = Object.assign({}, L.DEFAULT_SETTINGS, S.data || {});
  let live = ch.live && ch.live.skills ? ch.live.skills : null, liveSrc = live ? 'bot report' : '', liveErr = '';
  if (wantLive) { const l = await liveSkills(ctx, name); if (l.skills) { live = l.skills; liveSrc = 'MCP (live)'; } else liveErr = l.err; }
  const r = L.recommendChar(d, ch, settings, { level: level || undefined, detail: true, live, primary: L.primaryFrom(casterPrimary(ctx), ch) });
  r.liveSrc = liveSrc; r.liveErr = liveErr; r.rev = S.rev; r.levels = d.levels; r.books = d.books;
  r.skills.forEach(s => { const sk = d.skills[s.id]; s.routesFull = (sk.routes || []).map(x => ({ route: x.route, name: x.name, group: x.group, maxEnchant: x.maxEnchant, plus1: x.plus1, plusMax: x.plusMax })); });
  return r;
}

// ------------------------------------------------------------------------------------------------- write
/** posted settings -> { ok, settings } | { ok: false, errors } */
function seSanitize(input) {
  const errors = [], r = input && typeof input === 'object' && !Array.isArray(input) ? input : null;
  if (!r) return { ok: false, errors: ['settings must be an object'] };
  const n = (v, label, lo, hi, def) => {
    if (v === undefined || v === null || v === '') return def;
    const x = Number(String(v).replace(/[\s,_]/g, '').replace(/^(\d+(?:\.\d+)?)m$/i, (_, a) => String(a * 1e6)).replace(/^(\d+(?:\.\d+)?)k$/i, (_, a) => String(a * 1e3)));
    if (!Number.isFinite(x)) { errors.push(`${label}: "${String(v).slice(0, 20)}" is not a number`); return def; }
    if (x < lo || x > hi) { errors.push(`${label}: ${lo}..${hi}`); return def; }
    return Math.round(x);
  };
  const out = { _readme: 'Skill enchant settings (dashboard #/skillenchant). MANUAL ONLY (user 2026-10-12: enchanting is never automatic): auto is always false, minChance = the recommendation limit, each enchant is ONE explicit !skillenchant order. chars.<Name>: { auto: false = never (the order refuses), minChance, routes: { <skillId>: route (0 = never enchant this skill) } }.',
    auto: false, minChance: n(r.minChance, 'minimum chance %', 1, 100, 80), reserveAdena: n(r.reserveAdena, 'adena reserve', 0, 2e9, 5000000), maxTriesPerVisit: n(r.maxTriesPerVisit, 'tries per town visit', 1, 100, 6), chars: {} };
  const C = r.chars && typeof r.chars === 'object' && !Array.isArray(r.chars) ? r.chars : {};
  if (Object.keys(C).length > 500) errors.push('characters: at most 500');
  Object.keys(C).forEach(k => {
    if (!NAME_RE.test(k)) { errors.push(`"${k.slice(0, 40)}" is not a character name`); return; }
    const c = C[k] && typeof C[k] === 'object' ? C[k] : {}, o = {};
    if (c.auto === false) o.auto = false;   // only "never"; there is no auto any more (MANUAL-ONLY 2026-10-12)
    const mc = n(c.minChance, `${k} minimum chance`, 1, 100, null); if (mc !== null) o.minChance = mc;
    const R = c.routes && typeof c.routes === 'object' && !Array.isArray(c.routes) ? c.routes : {}, ro = {};
    Object.keys(R).forEach(id => {
      if (!/^\d{1,5}$/.test(id)) { errors.push(`${k}: skill "${id.slice(0, 10)}"`); return; }
      const v = R[id]; if (v === null || v === undefined || v === '') return;   // blank = recommended
      const x = Number(v); if (!Number.isInteger(x) || x < 0 || x > 9) { errors.push(`${k} skill ${id}: route 0..9`); return; }
      ro[id] = x;
    });
    if (Object.keys(ro).length) o.routes = ro;
    if (Object.keys(o).length) out.chars[k] = o;
  });
  out._updated = isoNow();
  return errors.length ? { ok: false, errors } : { ok: true, settings: out };
}
function rebuildPlan(ctx, settings) {
  const d = data(ctx); if (!d) return null;
  const cp = casterPrimary(ctx);
  const plan = L.buildPlanFile(d, chars(ctx), settings, classTree(ctx), isoNow(), { primaryOf: (ch) => L.primaryFrom(cp, ch) });
  guard(ctx).atomicWrite(planFile(ctx), JSON.stringify(plan, null, 1) + '\n');
  return plan;
}
function bad(code, error, extra) { return Object.assign({ code, error }, extra || {}); }
function post(ctx, b) {
  if (!b || typeof b !== 'object') return bad(400, 'bad body');
  const F = settingsFile(ctx), Gd = guard(ctx), by = String(b.by || 'dashboard').slice(0, 40);
  fs.mkdirSync(path.dirname(F), { recursive: true });
  let result = null;
  try {
    Gd.withLock(F, () => {
      const R = readSettings(ctx);
      if (R.broken) { result = bad(500, `${path.basename(F)} does not parse (${R.broken}) — fix or restore it from history/ first`); return; }
      if (b.rev !== undefined && b.rev !== null && String(b.rev) !== R.rev) { result = bad(409, 'the skill enchant settings were changed meanwhile — reload and try again', { rev: R.rev, conflict: true }); return; }
      const s = seSanitize(b.settings);
      if (!s.ok) { result = bad(400, s.errors.join('; '), { errors: s.errors }); return; }
      const hist = R.exists ? Gd.saveHistory(F, path.dirname(F), 50) : null;
      const txt = JSON.stringify(s.settings, null, 1) + '\n';
      Gd.atomicWrite(F, txt);
      let plan = null; try { plan = rebuildPlan(ctx, s.settings); } catch (e) { }
      try { fs.appendFileSync(path.join(ctx.LOGS, 'dashboard_commands.log'), `${isoNow()}\tskillenchant\tsave\t${by}: auto ${s.settings.auto} min ${s.settings.minChance}% reserve ${s.settings.reserveAdena}; ${Object.keys(s.settings.chars).length} character entries\r\n`); } catch (e) { }
      result = { code: 200, ok: true, rev: sha(txt), settings: s.settings, history: hist ? path.basename(hist) : null, plan: plan ? Object.keys(plan.chars).length : 0 };
    }, { who: 'skillenchant save' });
  } catch (e) { return bad(500, e.message); }
  return result;
}

async function handle(req, res, url, ctx) {
  const p = url.pathname;
  if (STATIC[p]) {
    res.writeHead(200, { 'Content-Type': STATIC[p], 'Cache-Control': 'no-cache' });
    res.end(fs.readFileSync(path.join(ctx.DIR || __dirname, path.basename(p))));
    return true;
  }
  if (p !== '/api/skillenchant') return false;
  if (!ctx.allowed(req, url)) { ctx.send(res, 401, 'text/plain; charset=utf-8', 'Access denied'); return true; }
  if (req.method === 'GET') {
    try {
      const name = url.searchParams.get('name');
      if (name) { const lv = Number(url.searchParams.get('level')) || 0; const r = await detail(ctx, name, lv >= 76 && lv <= 99 ? lv : 0, url.searchParams.get('live') === '1'); ctx.json(res, r.error ? 404 : 200, r); }
      else { const r = info(ctx); ctx.json(res, r.error ? 500 : 200, r); }
    } catch (e) { ctx.json(res, 500, { error: e.message }); }
    return true;
  }
  if (req.method !== 'POST') { ctx.json(res, 405, { error: 'GET or POST' }); return true; }
  let b = {}; try { let t = ''; for await (const c of req) t += c; b = JSON.parse(t || '{}'); } catch (e) { ctx.json(res, 400, { error: 'bad JSON' }); return true; }
  try { const r = post(ctx, b) || bad(500, 'no result'); const code = r.code || 200; delete r.code; ctx.json(res, code, r); } catch (e) { ctx.json(res, 500, { error: e.message }); }
  return true;
}
