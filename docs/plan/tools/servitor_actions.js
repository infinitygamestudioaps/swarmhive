// SERVITOR ACTIONS (user 2026-10-10: "some of the servitors have skills themselves that can be used at higher level").
// L2Swarm's JS API can READ a servitor's skills (L2PartyPet.Skills: L2EntityCollection<L2Skill>, docs/js-api/entities.txt) but has no packet
// to cast one: the High Five client casts a servitor / pet skill with RequestActionUse (0x56, d actionId, d ctrl, c shift — Data/base.db
// PacketsGSClient line '56=RequestActionUse=d(Action:Get.F9)...'), and the SERVER maps each action id to the skill (L2J RequestActionUse.java:
// 'case 1034: // Magnus the Unicorn - Whiplash -> useSkill("PhysicalSpecial1", false)'). This tool turns that server table into data:
//   Scripts/data/servitor_actions.json = { actions: [{ action, servitor, skill, slot | skillId, owner (cast on the summoner), pet (pet, not a
//   servitor) }] }  — swarm.js matches the servitor's own skill NAMES (L2PartyPet.Skills) to `skill` and sends Send.RequestActionUse(action).
// Source: Scripts/data/dp/sys/RequestActionUse.java (copy of github.com/Shagooh/l2j-server-game master,
//   src/main/java/com/l2jserver/gameserver/network/clientpackets/RequestActionUse.java, fetched 2026-10-10 — the same project as the datapack).
// Run: node docs/plan/tools/servitor_actions.js
'use strict';
const fs = require('fs'), path = require('path');
const ROOT = path.resolve(__dirname, '..', '..', '..');
const SRC = path.join(ROOT, 'Scripts', 'data', 'dp', 'sys', 'RequestActionUse.java'), OUT = path.join(ROOT, 'Scripts', 'data', 'servitor_actions.json');
function parse(java) {
  const lines = java.split(/\r?\n/), out = [];
  for (let i = 0; i < lines.length; i++) {
    const m = /^\s*case (\d+):\s*\/\/\s*(.+?)\s+-\s+(.+?)\s*$/.exec(lines[i]);
    if (!m) continue;
    let call = null;
    for (let j = i + 1; j < Math.min(lines.length, i + 12); j++) {
      if (/^\s*case \d+:/.test(lines[j])) break;
      const u = /useSkill\(\s*("([^"]+)"|(\d+))\s*(,\s*activeChar)?\s*,\s*(true|false)\s*\)/.exec(lines[j]);
      if (u) { call = { slot: u[2] || null, skillId: u[3] ? Number(u[3]) : null, owner: !!u[4], pet: u[5] === 'true' }; break; }
    }
    if (!call) continue;
    out.push(Object.assign({ action: Number(m[1]), servitor: m[2].trim(), skill: m[3].trim() }, call));
  }
  return out;
}
if (require.main === module) {
  const actions = parse(fs.readFileSync(SRC, 'utf8'));
  const j = { _about: 'Servitor / pet skill -> RequestActionUse action id (generated by docs/plan/tools/servitor_actions.js from the L2J High Five RequestActionUse.java table; swarm.js matches the servitor\'s own skill names)',
    generated: new Date().toISOString(), source: 'Scripts/data/dp/sys/RequestActionUse.java (github.com/Shagooh/l2j-server-game)', actions };
  fs.writeFileSync(OUT, JSON.stringify(j, null, 1));
  console.log(`wrote ${path.relative(ROOT, OUT)}: ${actions.length} actions (${actions.filter(a => !a.pet).length} servitor, ${actions.filter(a => a.pet).length} pet)`);
}
module.exports = { parse };
