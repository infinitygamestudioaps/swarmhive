// EPIC SYNC (2026-10-10): Dashboard/raidspage.js carries a copy of Scripts/data/epic_tactics.json and of the EPIC-PURE block of
// Scripts_dev/swarm.js (the page files are served without a data API, and the requirement check must be the SAME code the bots run).
//   node docs/plan/tools/epic_sync.js           -> rewrites the EPIC-GUIDE block in Dashboard/raidspage.js
//   node docs/plan/tools/epic_sync.js --check   -> exit 1 when the copy differs (test_epic_tactics.js runs this)
// Run it after every edit of epic_tactics.json or of the EPIC-PURE block. Never edit the block in raidspage.js by hand.
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..', '..', '..');
const SW = path.join(ROOT, 'Scripts_dev', 'swarm.js'), DATA = path.join(ROOT, 'Scripts', 'data', 'epic_tactics.json'), PAGE = path.join(ROOT, 'Dashboard', 'raidspage.js');
const B = '// EPIC-GUIDE-BEGIN', E = '// EPIC-GUIDE-END';
function build() {
  const src = fs.readFileSync(SW, 'utf8').replace(/\r\n/g, '\n');
  const a = src.indexOf('// EPIC-PURE-BEGIN'), b = src.indexOf('// EPIC-PURE-END');
  if (a < 0 || b < a) throw new Error('EPIC-PURE block not found in Scripts_dev/swarm.js');
  const pure = src.slice(a, b + '// EPIC-PURE-END'.length);
  const J = JSON.parse(fs.readFileSync(DATA, 'utf8').replace(/^﻿/, ''));
  return `${B} (generated by docs/plan/tools/epic_sync.js from Scripts/data/epic_tactics.json + the EPIC-PURE block of swarm.js — do not edit)\n` +
    `  const EPIC_TACTICS = ${JSON.stringify(J)};\n` + pure.split('\n').map(l => l ? '  ' + l : l).join('\n') + `\n  ${E}`;
}
function current(page) { const a = page.indexOf(B), b = page.indexOf(E); return a < 0 || b < a ? null : { a, b: b + E.length, text: page.slice(a, b + E.length) }; }
const check = process.argv.includes('--check');
const page = fs.readFileSync(PAGE, 'utf8'), crlf = page.includes('\r\n'), P = page.replace(/\r\n/g, '\n');
const want = build(), cur = current(P);
if (check) {
  if (!cur) { console.log('FAIL epic_sync: no EPIC-GUIDE block in Dashboard/raidspage.js'); process.exit(1); }
  if (cur.text !== want) { console.log('FAIL epic_sync: Dashboard/raidspage.js EPIC-GUIDE block is out of date — run node docs/plan/tools/epic_sync.js'); process.exit(1); }
  console.log('ok   epic_sync: raidspage.js carries the current epic_tactics.json + EPIC-PURE block'); process.exit(0);
}
if (!cur) { console.error('no EPIC-GUIDE-BEGIN / END markers in Dashboard/raidspage.js'); process.exit(1); }
let out = P.slice(0, cur.a) + want + P.slice(cur.b);
if (crlf) out = out.replace(/\n/g, '\r\n');
fs.writeFileSync(PAGE, out);
console.log('raidspage.js EPIC-GUIDE block updated');
